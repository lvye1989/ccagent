import { readFile, writeFile } from 'node:fs/promises';
import { currentMigrationContract } from './lib/migration-contract';

const file = 'src/core/db/migration-contract.ts', contract = currentMigrationContract();
const content = '// Generated by scripts/update-migration-contract.ts --write after reviewing migrations. No credentials.\n'
  + `export const requiredDatabaseContract = ${JSON.stringify(contract, null, 2)} as const;\n`;
if (process.argv.includes('--write')) await writeFile(file, content, 'utf8');
else if ((await readFile(file, 'utf8')).replaceAll('\r\n', '\n') !== content) throw new Error('MIGRATION_CONTRACT_OUTDATED');
console.log(JSON.stringify({ checked: true, written: process.argv.includes('--write'), requiredTables: contract.tables.length, migrations: contract.migrations.length }));
